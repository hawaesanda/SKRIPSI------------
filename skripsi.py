from sklearn.preprocessing import StandardScaler

def standardize_spectra(dataframe):
    names = dataframe['Name']
    spectra = dataframe.drop(columns=['Name'])

    # Standardize per baris (transpos dulu karena StandardScaler bekerja per kolom)
    scaler = StandardScaler()
    standardized = pd.DataFrame(
        scaler.fit_transform(spectra.T).T,
        columns=spectra.columns,
        index=spectra.index
    )

    standardized.insert(0, 'Name', names)
    return standardized

