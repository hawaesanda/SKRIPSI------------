def transform_data(dataframe):

    rows = []

    wavelength_cols = [
        col for col in dataframe.columns
        if col != 'Name'
    ]

    for i in range(len(dataframe)):

        for col in wavelength_cols:

            rows.append([
                float(col),
                dataframe.iloc[i][col]
            ])

    return pd.DataFrame(
        rows,
        columns=[
            'Wavelength',
            'Absorbance'
        ]
    )

