"""### Langkah Perbaikan: Normalisasi Min-Max per Sampel
Kita akan menormalisasi setiap baris agar memiliki nilai minimum 0 dan maksimum 1 sebelum ditransformasi ke format long.
"""

def normalize_spectra(dataframe):
    # Pisahkan kolom Name
    names = dataframe['Name']
    spectra = dataframe.drop(columns=['Name'])

    # Normalisasi Min-Max per baris
    normalized = spectra.apply(lambda x: (x - x.min()) / (x.max() - x.min()), axis=1)

    # Gabungkan kembali
    normalized.insert(0, 'Name', names)
    return normalized

